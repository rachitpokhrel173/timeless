/**
 * Writes supabase/seed.sql from a database populated by `npm run db:seed`, so
 * `supabase db reset` (and `npm run db:reset`) reproduce the same website content.
 *
 *   npm run db:seed:sql
 *
 * Reference data that the migrations insert (roles, permissions, stages, sources, categories,
 * automation rules, checklists) is not repeated; references to category rows are written as
 * lookups by slug because their ids differ between databases.
 */
import { config } from "dotenv";
config({ path: [".env.local", ".env"], quiet: true });

import { writeFileSync } from "node:fs";
import postgres from "postgres";

const sql = postgres(process.env.DATABASE_URL!, { max: 1, onnotice: () => {} });

const SKIP = new Set([
  "permissions",
  "roles",
  "role_permissions",
  "user_roles",
  "profiles",
  "sales_pipeline_stages",
  "campaign_sources",
  "inventory_categories",
  "expense_categories",
  "automation_rules",
  "automation_runs",
  "checklist_templates",
  "counters",
  "rate_limits",
  "login_attempts",
  "activity_logs",
  "notification_reads",
  "email_outbox",
  "backups",
  "event_types", // created by migration; image links are written as updates below
]);

/** Columns holding ids of migration-created rows → rewritten as lookups. */
const LOOKUPS: Record<string, { table: string; key: string }> = {
  "inventory_items.category_id": { table: "inventory_categories", key: "slug" },
  "expenses.category_id": { table: "expense_categories", key: "slug" },
};

const lit = (v: string | null, type: string) => (v === null ? "null" : `'${v.replace(/'/g, "''")}'::${type}`);

async function main() {
  const tables = (await sql`select tablename from pg_tables where schemaname = 'public' order by tablename`).map((r) => r.tablename as string).filter((t) => !SKIP.has(t));
  const edges = await sql`
    select c.conrelid::regclass::text as child, c.confrelid::regclass::text as parent
    from pg_constraint c where c.contype = 'f' and c.connamespace = 'public'::regnamespace`;
  // Topological order: parents first
  const ordered: string[] = [];
  const pending = new Set(tables);
  const strip = (t: string) => t.replace(/^public\./, "");
  while (pending.size) {
    const ready = [...pending].filter((t) => !edges.some((e) => strip(e.child) === t && strip(e.parent) !== t && pending.has(strip(e.parent))));
    if (!ready.length) throw new Error(`Circular foreign keys among: ${[...pending].join(", ")}`);
    for (const t of ready.sort()) {
      ordered.push(t);
      pending.delete(t);
    }
  }

  const out: string[] = [
    "-- supabase/seed.sql — generated by `npm run db:seed:sql`. Do not edit by hand.",
    "--",
    "-- Website content imported from the original site. No business records (customers, bookings,",
    "-- payments…) are included — those are created in the admin.",
    "-- No passwords or real customer data are included. Run with `supabase db reset` or `npm run db:reset`.",
    "",
    "begin;",
    "",
  ];

  // Lookup maps for category ids
  const lookupMaps: Record<string, Map<string, string>> = {};
  for (const { table, key } of Object.values(LOOKUPS)) {
    lookupMaps[table] = new Map((await sql.unsafe(`select id::text, ${key} from public.${table}`)).map((r) => [r.id as string, r[key] as string]));
  }

  for (const table of ordered) {
    const cols = await sql`
      select a.attname as name, format_type(a.atttypid, a.atttypmod) as type
      from pg_attribute a where a.attrelid = ${`public.${table}`}::regclass and a.attnum > 0 and not a.attisdropped and a.attgenerated = ''
      order by a.attnum`;
    const rows = await sql.unsafe(`select ${cols.map((c) => `"${c.name}"::text as "${c.name}"`).join(", ")} from public.${table} order by 1`);
    if (!rows.length) continue;
    out.push(`-- ${table} (${rows.length})`);
    for (const row of rows) {
      const values = cols.map((c) => {
        const lookup = LOOKUPS[`${table}.${c.name}`];
        const v = row[c.name] as string | null;
        if (lookup && v) return `(select id from public.${lookup.table} where ${lookup.key} = '${lookupMaps[lookup.table].get(v)}')`;
        return lit(v, c.type as string);
      });
      out.push(`insert into public.${table} (${cols.map((c) => `"${c.name}"`).join(", ")}) values (${values.join(", ")}) on conflict do nothing;`);
    }
    out.push("");
  }

  const eventTypes = await sql`select slug, image_id::text from public.event_types where image_id is not null`;
  out.push("-- event type photos");
  for (const t of eventTypes) out.push(`update public.event_types set image_id = '${t.image_id}' where slug = '${t.slug}';`);
  out.push("", "commit;", "");

  writeFileSync("supabase/seed.sql", out.join("\n"));
  console.log(`Wrote supabase/seed.sql (${ordered.length} tables).`);
  await sql.end();
}

main().catch(async (e) => {
  console.error(e);
  await sql.end();
  process.exit(1);
});
